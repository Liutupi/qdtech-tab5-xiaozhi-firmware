#!/usr/bin/env python3
"""Generate the small NABO avatar shown on the 每日推送 page.

Source: assets/nabo/push-avatar-source.png (the neutral bust master at 2x). Output:
main/boards/qdtech/tab5/nabo_push_avatar.c, one RGB565A8 image of 134x172.
"""

from pathlib import Path

from PIL import Image

from nabo_image_codec import rgb565a8

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/nabo/push-avatar-source.png"
OUTPUT = ROOT / "main/boards/qdtech/tab5/nabo_push_avatar.c"
SIZE = (134, 172)


def main() -> None:
    image = Image.open(SOURCE).convert("RGBA").resize(SIZE, Image.LANCZOS)
    data = rgb565a8(image)
    lines = [
        "// Generated by scripts/prepare_nabo_push_avatar.py from assets/nabo/push-avatar-source.png.",
        '#include "lvgl.h"',
        "",
        "static const uint8_t nabo_push_avatar_data[] __attribute__((aligned(4))) = {",
    ]
    for start in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[start:start + 16]) + ",")
    lines += [
        "};",
        "const lv_image_dsc_t nabo_push_avatar = {",
        "    .header.magic = LV_IMAGE_HEADER_MAGIC,",
        "    .header.cf = LV_COLOR_FORMAT_RGB565A8,",
        f"    .header.stride = {SIZE[0] * 2},",
        f"    .header.w = {SIZE[0]},",
        f"    .header.h = {SIZE[1]},",
        "    .data_size = sizeof(nabo_push_avatar_data),",
        "    .data = nabo_push_avatar_data,",
        "};",
        "",
    ]
    OUTPUT.write_text("\n".join(lines))
    print(f"nabo_push_avatar: {SIZE[0]}x{SIZE[1]}, {len(data)} bytes -> {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
